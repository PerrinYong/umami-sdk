#!/usr/bin/env python3
"""Generate embedded cross-language policy constants from the canonical JSON files."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "schema"


def compact_json(path: Path) -> str:
    value = json.loads(path.read_text(encoding="utf-8"))
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True)


def outputs() -> dict[Path, str]:
    registry = compact_json(SCHEMA / "event-registry.json")
    policy = compact_json(SCHEMA / "privacy-policy.json")

    ts = (
        "// Generated by tools/generate_policy.py. Do not edit.\n"
        f"export const EVENT_REGISTRY_JSON = {json.dumps(registry)};\n"
        f"export const PRIVACY_POLICY_JSON = {json.dumps(policy)};\n"
    )
    py = (
        '"""Generated by tools/generate_policy.py. Do not edit."""\n\n'
        f"EVENT_REGISTRY_JSON = {registry!r}\n"
        f"PRIVACY_POLICY_JSON = {policy!r}\n"
    )
    cs = (
        "// Generated by tools/generate_policy.py. Do not edit.\n"
        "namespace Pystone.Analytics;\n\n"
        "internal static class GeneratedPolicy\n"
        "{\n"
        f'    internal const string EventRegistryJson = "{registry.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))}";\n'
        f'    internal const string PrivacyPolicyJson = "{policy.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))}";\n'
        "}\n"
    )

    return {
        ROOT / "typescript" / "src" / "core" / "generated-policy.ts": ts,
        ROOT / "python" / "src" / "pystone_analytics" / "_generated_policy.py": py,
        ROOT / "dotnet" / "Pystone.Analytics" / "GeneratedPolicy.cs": cs,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    stale: list[str] = []
    for path, expected in outputs().items():
        actual = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if actual != expected:
                stale.append(str(path.relative_to(ROOT.parent)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")

    if stale:
        print("Generated policy files are stale:", file=sys.stderr)
        for path in stale:
            print(f"  {path}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
